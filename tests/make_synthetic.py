"""Write fake subjects in the exact WESAD pickle format, for smoke-testing only.

Each subject gets its own physiological offsets (resting HR, EDA level, skin temperature)
that are larger than the stress effect. That is the situation in which random window
k-fold looks great and leave-one-subject-out does not. The numbers this produces say
nothing about WESAD; run on the real data before publishing anything.
"""
import pickle
import sys
from pathlib import Path

import numpy as np

FS = {"ACC": 32, "BVP": 64, "EDA": 4, "TEMP": 4}


def subject(rng, base_min=12, stress_min=6, gap_min=1):
    hr0, eda0, temp0 = rng.normal(72, 9), rng.lognormal(0.5, 0.8), rng.normal(33, 1.0)
    segs = [(0, gap_min), (1, base_min), (0, gap_min), (2, stress_min), (0, gap_min)]
    total_s = sum(m for _, m in segs) * 60
    label = np.concatenate([np.full(int(m * 60 * 700), lab) for lab, m in segs])
    stress = np.concatenate([np.full(int(m * 60), lab == 2) for lab, m in segs]).astype(float)  # 1 Hz mask

    def per_second(base, effect, noise):
        return base + effect * stress + rng.normal(0, noise, len(stress)).cumsum() * 0.02

    hr = per_second(hr0, 7.0, 1.0)
    t = np.arange(int(total_s * FS["BVP"])) / FS["BVP"]
    phase = 2 * np.pi * np.cumsum(np.interp(t, np.arange(len(hr)), hr) / 60) / FS["BVP"]
    bvp = np.sin(phase) + 0.15 * rng.normal(size=t.size)
    eda = np.interp(np.arange(int(total_s * 4)) / 4, np.arange(len(stress)),
                    per_second(eda0, 0.35 * eda0, 0.5)) + 0.01 * rng.normal(size=int(total_s * 4))
    temp = np.interp(np.arange(int(total_s * 4)) / 4, np.arange(len(stress)),
                     per_second(temp0, -0.3, 0.2))
    n_acc = int(total_s * FS["ACC"])
    acc = rng.normal(0, 3 + 2 * rng.random(), (n_acc, 3)) + np.array([0, 0, 64])
    wrist = {"ACC": acc, "BVP": bvp[:, None], "EDA": eda[:, None], "TEMP": temp[:, None]}
    return {"signal": {"wrist": wrist}, "label": label}


if __name__ == "__main__":
    root = Path(sys.argv[1] if len(sys.argv) > 1 else "synthetic_wesad")
    root.mkdir(parents=True, exist_ok=True)
    (root / "SYNTHETIC_DATA_NOT_WESAD").write_text("Generated by tests/make_synthetic.py\n")
    rng = np.random.default_rng(42)
    for k in [s for s in range(2, 18) if s != 12]:
        d = root / f"S{k}"
        d.mkdir(exist_ok=True)
        data = subject(rng)
        data["subject"] = f"S{k}"
        with open(d / f"S{k}.pkl", "wb") as f:
            pickle.dump(data, f)
    print(f"Wrote 15 synthetic subjects to {root}/")
